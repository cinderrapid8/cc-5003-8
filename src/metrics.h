#ifndef AEC_DEMO_METRICS_H
#define AEC_DEMO_METRICS_H

#include <cstdint>
#include <string>
#include <vector>

#include "aec_processor.h"
#include "signal_gen.h"

struct SegmentMetrics {
    std::string label;
    double start_s = 0;
    double end_s = 0;
    double mic_rms = 0;
    double out_rms = 0;
    double echo_rms = 0;     // ground-truth echo component in the mic
    double near_rms = 0;     // ground-truth near component in the mic
    double erle_db = 0;      // 10 log10(mic_echo_power / residual_power)
    double echo_leak_db = 0; // residual level relative to original echo
    double near_keep_db = 0; // near power ratio, dB (0 = fully retained)
    double corr_out_near = 0; // correlation of output with true near speech
    double corr_out_echo = 0; // correlation of output with true echo
    size_t samples = 0;
};

struct RunMetrics {
    std::vector<SegmentMetrics> segments;
    size_t limited_samples = 0;   // samples marked REFERENCE_MISSING
    size_t rate_adapted_samples = 0;
    size_t tail_samples = 0;
    size_t total_samples = 0;
    double overall_erle_db = 0;   // over far-only segments only
    double overall_near_keep_db = 0; // over near-active segments only
    std::string verdict;
};

// All comparisons use the ground-truth decomposition generated by the
// scenario builder, so residual echo and near-end retention are measured
// separately instead of inferring success from output energy.
RunMetrics evaluate(const GeneratedSignals& gen, const AecRunResult& run);

#endif
